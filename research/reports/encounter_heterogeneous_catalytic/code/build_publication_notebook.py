def main() -> None:
    NOTEBOOK.parent.mkdir(parents=True, exist_ok=True)
    notebook = build_notebook()
    independent_rebuild = build_notebook()
    serialized_source = nbformat.writes(notebook)
    if serialized_source != nbformat.writes(independent_rebuild):
        raise RuntimeError("Two independent source-notebook builds were not deterministic")
    source_sha256 = hashlib.sha256(serialized_source.encode("utf-8")).hexdigest()
    nbformat.validate(notebook)
    nbformat.write(notebook, NOTEBOOK)

    with _bound_kernel_spec() as (kernel_name, kernel_spec):
        client = NotebookClient(
            notebook,
            timeout=180,
            kernel_name=kernel_name,
            allow_errors=False,
            record_timing=False,
            resources={"metadata": {"path": str(REPO)}},
        )
        executed = client.execute()
    errors = [
        output
        for cell in executed.cells
        if cell.cell_type == "code"
        for output in cell.get("outputs", [])
        if output.get("output_type") == "error"
    ]
    if errors:
        raise RuntimeError(f"Notebook execution produced {len(errors)} error output(s)")

    code_cells = [cell for cell in executed.cells if cell.cell_type == "code"]
    if any(cell.get("execution_count") is None for cell in code_cells):
        raise RuntimeError("At least one code cell was not executed")

    runtime_lines = [
        line
        for cell in code_cells
        for output in cell.get("outputs", [])
        if output.get("output_type") == "stream"
        for line in output.get("text", "").splitlines()
        if line.startswith("KERNEL_RUNTIME_JSON=")
    ]
    if len(runtime_lines) != 1:
        raise RuntimeError(
            "Notebook execution did not emit exactly one kernel runtime marker"
        )
    kernel_runtime = json.loads(runtime_lines[0].removeprefix("KERNEL_RUNTIME_JSON="))
    builder_executable = str(Path(sys.executable).absolute())
    if not os.path.samefile(kernel_runtime["executable"], builder_executable):
        raise RuntimeError(
            "Notebook kernel executable differs from the builder executable: "
            f"kernel={kernel_runtime['executable']} builder={builder_executable}"
        )
    builder_packages = {
        name: importlib.metadata.version(name) for name in DIRECT_RUNTIME_PACKAGES
    }
    if kernel_runtime["packages"] != builder_packages:
        raise RuntimeError(
            "Notebook kernel package versions differ from the builder environment"
        )

    executed.metadata["encounter_publication_validation"].update(
        {
            "executed": True,
            "code_cell_count": len(code_cells),
            "error_output_count": 0,
            "deterministic_source_rebuild_verified": True,
            "source_notebook_sha256": source_sha256,
            "builder_executable": builder_executable,
            "kernel_executable": kernel_runtime["executable"],
            "kernel_matches_builder": True,
            "execution_kernel_name": kernel_name,
            "kernel_spec_argv": kernel_spec["argv"],
            "direct_package_versions": builder_packages,
        }
    )
    nbformat.validate(executed)
    nbformat.write(executed, NOTEBOOK)
    print(f"Wrote executed notebook: {NOTEBOOK.relative_to(REPO)}")
    print(f"Executed code cells: {len(code_cells)}; error outputs: 0")


if __name__ == "__main__":
    main()
